#!/usr/bin/env -S uv run --active --with tomlkit python

"""Initialize a project from the devkit template."""

import keyword
import pathlib
import re
import shutil
import subprocess
import sys
from collections.abc import Iterator, Sequence
from typing import IO, Final

import tomlkit
import tomlkit.items

__all__: Final[tuple[str, ...]] = ()

# The name the template is written under. Every reference to it, with or without the `_tests` suffix, becomes
# the project's name.
PLACEHOLDER: Final[str] = "devkit"

_ROOT: Final[pathlib.Path] = pathlib.Path(__file__).resolve().parent.parent

_MAKEFILE: Final[pathlib.Path] = _ROOT / "Makefile"

_PYPROJECT: Final[pathlib.Path] = _ROOT / "pyproject.toml"

_README: Final[pathlib.Path] = _ROOT / "README.md"

_SCRIPT: Final[pathlib.Path] = pathlib.Path(__file__).resolve()

_SOURCE: Final[pathlib.Path] = _ROOT / "src"

# The Makefile section this script is reached through: it goes once the project exists, along with the
# catch-all rule that let the name pass as an argument.
_MAKEFILE_SECTION_HEADER: Final[str] = "###--INIT--"

_MAKEFILE_SECTION_FOOTER: Final[str] = "####"

# What is said about the template and not about the project built from it. Each block goes whole, with the
# blank line that followed it.
_README_BLOCK_PATTERN: Final[re.Pattern[str]] = re.compile(
    r"<!-- template:start -->\n.*?<!-- template:end -->\n\n?", flags=re.DOTALL
)

# A package name: an identifier the import system and the filesystem both accept as spelled.
_NAME_PATTERN: Final[re.Pattern[str]] = re.compile(r"^[a-z][a-z0-9_]*$")

# Only the placeholder itself is replaced, leaving a `_tests` suffix in place, so one pass rewrites both
# spellings and a name that contains the placeholder (`mydevkit`) is never rewritten twice.
_PLACEHOLDER_PATTERN: Final[re.Pattern[str]] = re.compile(rf"\b{PLACEHOLDER}(?=\b|_tests\b)")

# What a walk of the repository must not read: nothing in these is a reference to rewrite, and the lockfile
# is regenerated by `uv sync` rather than edited.
_SKIPPED_DIRECTORIES: Final[frozenset[str]] = frozenset(
    {".git", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".venv", "__pycache__"}
)

_SKIPPED_FILES: Final[frozenset[str]] = frozenset({"uv.lock"})


def main(arguments: Sequence[str]) -> int:
    if len(arguments) != 1:
        print("usage: make init <name>", file=sys.stderr)
        return 2

    name: Final[str] = arguments[0]
    try:
        _validate(name)

    except ValueError as exception:
        print(exception, file=sys.stderr)
        return 2

    print(f"Rewriting every `{PLACEHOLDER}` reference to `{name}`...")
    path: pathlib.Path
    for path in _get_text_paths():
        _rewrite(path, name=name)

    print("Renaming the packages...")
    (_SOURCE / f"{PLACEHOLDER}_tests").rename(_SOURCE / f"{name}_tests")
    (_SOURCE / PLACEHOLDER).rename(_SOURCE / name)
    # `uv run` built the template before this script started, and the metadata it left carries the old name.
    shutil.rmtree(_SOURCE / f"{PLACEHOLDER}.egg-info", ignore_errors=True)

    print("Describing the project in `pyproject.toml`...")
    _describe(name)

    print("Dropping the template-only parts of `README.md` and the `Makefile`...")
    _strip_readme()
    _strip_makefile()

    print("Removing this script...")
    _SCRIPT.unlink()

    print("Running `uv sync`...")
    if _uv_sync() != 0:
        print("Command `uv sync` failed; the project is renamed, but the environment is stale.", file=sys.stderr)
        return 1

    print(f"The project `{name}` is ready. Review the changes with `git status`, then commit them.")
    return 0


def _validate(name: str) -> None:
    if _NAME_PATTERN.match(name) is None:
        message: str = f"Name `{name}` is not a package name: use lowercase letters, digits and underscores."
        raise ValueError(message)

    if keyword.iskeyword(name):
        message = f"Name `{name}` is a Python keyword."
        raise ValueError(message)


def _get_text_paths() -> Iterator[pathlib.Path]:
    # Every file that is not generated or a cache, so no reference is left behind in a place this script did
    # not think of; the lockfile is the one exception, and `uv sync` rewrites it.
    pending: Final[list[pathlib.Path]] = [_ROOT]
    directory: pathlib.Path
    while len(pending) > 0:
        directory = pending.pop()
        path: pathlib.Path
        for path in sorted(directory.iterdir()):
            if path.is_dir():
                if path.name not in _SKIPPED_DIRECTORIES:
                    pending.append(path)

            elif path.name not in _SKIPPED_FILES and path != _SCRIPT:
                yield path


def _rewrite(path: pathlib.Path, *, name: str) -> None:
    try:
        source: Final[str] = path.read_text(encoding="utf-8")

    # A binary file holds no reference to rewrite, and reading one as text is the only way to find out.
    except UnicodeDecodeError:
        return

    rewritten: Final[str] = _PLACEHOLDER_PATTERN.sub(name, source)
    if rewritten != source:
        path.write_text(rewritten, encoding="utf-8")


def _describe(name: str) -> None:
    file: IO[str]
    with _PYPROJECT.open(encoding="utf-8") as file:
        pyproject: Final[tomlkit.TOMLDocument] = tomlkit.load(file)

    project: Final[object] = pyproject["project"]
    if not isinstance(project, tomlkit.items.Table):
        message: Final[str] = "File `pyproject.toml` has no `[project]` table."
        raise TypeError(message)

    project["description"] = f"{name.replace('_', ' ').capitalize()}."
    with _PYPROJECT.open(mode="wt", encoding="utf-8") as file:
        tomlkit.dump(pyproject, file)


def _strip_readme() -> None:
    source: Final[str] = _README.read_text(encoding="utf-8")
    _README.write_text(_README_BLOCK_PATTERN.sub("", source), encoding="utf-8")


def _strip_makefile() -> None:
    lines: Final[list[str]] = _MAKEFILE.read_text(encoding="utf-8").splitlines(keepends=True)
    start: Final[int] = _find_line(lines, prefix=_MAKEFILE_SECTION_HEADER, start=0)
    end: int = _find_line(lines, prefix=_MAKEFILE_SECTION_FOOTER, start=start + 1)
    # The blank line separating the section from the next one goes with it.
    if end + 1 < len(lines) and len(lines[end + 1].strip()) == 0:
        end += 1

    _MAKEFILE.write_text("".join([*lines[:start], *lines[end + 1 :]]), encoding="utf-8")


def _find_line(lines: Sequence[str], *, prefix: str, start: int) -> int:
    index: int
    for index in range(start, len(lines)):
        if lines[index].startswith(prefix):
            return index

    message: Final[str] = f"No line starting with `{prefix}` at or after line {start + 1} of `{_MAKEFILE}`."
    raise ValueError(message)


def _uv_sync() -> int:
    return subprocess.run(args=("uv", "sync"), stdout=sys.stdout, stderr=sys.stderr, check=False).returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
